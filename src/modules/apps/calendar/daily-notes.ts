/** 今日のひとこと(`YYYY-MM-DD`)。 */
export function dailyNote(date: string): string {
  const fixed = FIXED[date.slice(5)];
  if (fixed) return fixed;
  const pool = MONTHLY[Number(date.slice(5, 7))];
  return pool[(Number(date.slice(8, 10)) - 1) % pool.length];
}
